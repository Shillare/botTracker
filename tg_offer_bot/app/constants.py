# --- Валюта --------------------------------------------------------------------
# Telegram блокирует (PEER_FLOOD) сообщения от имени бизнес-аккаунта, если
# получатель никогда не писал боту, а в тексте есть слово валюты + внешняя
# ссылка.
#
# Проверено на реальном аккаунте 2026-10-14 отправкой от имени аккаунта
# получателю, который боту не писал:
#   «2500 Stars» + ссылка -> PEER_FLOOD
#   «2500 ⭐»     + ссылка -> PEER_FLOOD   (звёздочка тоже перестала проходить)
#   «2500 XTR»    + ссылка -> OK
#   «2500 Ѕtarѕ»  + ссылка -> OK
#
# Выбран гомоглиф: «Ѕtarѕ» клиент рисует как обычное «Stars», но строковый
# фильтр Telegram его не узнаёт. «XTR» тоже проходит и выглядит честной
# латиницей — переключается одной строкой ``STARS_LABEL=XTR`` в ``.env``.
# Обычное «Stars» ставить нельзя: карточка не дойдёт.
